#!/usr/bin/env python3
"""Generate undocumented_returns.lua: what the C_* functions Blizzard's UI calls but the API docs leave out return.

Blizzard_APIDocumentationGenerated gives every documented function's returns, and stubgen answers from those. The
client also has functions the docs leave out (C_PetJournal.GetNumPets is one), which Blizzard's own UI calls; the
pinned Ketho/vscode-wow-api annotations type many of them from the wiki. This writes the return list of each such
call the annotations type, so the sim's stub answers with the client's shape (GetNumPets: two numbers) instead of a
guess from the name.

    python3 .agents/skills/wow-forever-addon/tooling/forever_sim/gen_undocumented_returns.py \\
        --annotations .types/vscode-wow-api --ui tools/.cache/forever_sim/wow-ui-source
    python3 .agents/skills/wow-forever-addon/tooling/forever_sim/sync.py manifest

The file is committed: regenerate it when the annotation pin or the UI source moves, never by hand.
"""

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from forever_sim.fetch import API_CALL  # noqa: E402

OUTPUT = Path(__file__).resolve().with_name("undocumented_returns.lua")
DOC_NAMESPACE = re.compile(r'Namespace = "([^"]+)"')
DOC_FUNCTION = re.compile(r'Name = "(\w+)",\s*\n\s*Type = "Function"')
ANNOTATED = re.compile(r"((?:---[^\n]*\n)+)function ([\w.]+)\(")
RETURN = re.compile(r"^---@return\s+(\S+)", re.M)
# Annotation types and the docs type stubgen's zero value takes for each; any other name is a docs structure or enum.
PLAIN = {"number": "number", "boolean": "bool", "string": "string", "table": "table"}


def doc_type(annotation: str) -> tuple[str, bool]:
    nilable = annotation.endswith("?") or annotation.endswith("|nil")
    name = annotation.removesuffix("?").removesuffix("|nil").removeprefix("Enum.")
    if name.endswith("[]") or name.startswith("table<"):
        return "table", nilable
    return PLAIN.get(name, name), nilable


def read(annotations: Path, ui: Path) -> dict[str, list[tuple[str, bool]]]:
    addons = ui / "Interface" / "AddOns"
    documented, called = set(), set()
    for path in (addons / "Blizzard_APIDocumentationGenerated").glob("*.lua"):
        text = path.read_text(errors="replace")
        namespace = DOC_NAMESPACE.search(text)
        if namespace:
            documented.update(f"{namespace.group(1)}.{name}" for name in DOC_FUNCTION.findall(text))
    for path in addons.rglob("*.lua"):
        if "APIDocumentation" not in path.parts[-2]:
            called.update(f"{ns}.{name}" for ns, name in API_CALL.findall(path.read_text(errors="replace")))
    wanted = called - documented
    out = {}
    for path in sorted((annotations / "Annotations").rglob("*.lua")):
        for comments, name in ANNOTATED.findall(path.read_text(errors="replace")):
            returns = RETURN.findall(comments)
            if name in wanted and name not in out and returns:
                out[name] = [doc_type(r) for r in returns if r != "..."]
    return out


def render(returns: dict[str, list[tuple[str, bool]]]) -> str:
    lines = [
        "-- Generated by gen_undocumented_returns.py from the pinned Ketho/vscode-wow-api annotations, not by hand:",
        "-- the returns of each C_* function Blizzard's UI calls that Blizzard_APIDocumentationGenerated leaves out.",
        "return {",
    ]
    for name in sorted(returns):
        values = [f'{{ Type = "{t}"' + (", Nilable = true" if nilable else "") + " }" for t, nilable in returns[name]]
        line = f'\t["{name}"] = {{ {", ".join(values)} }},'
        # One line when it fits the 120 columns stylua and luacheck allow (a tab counts as 4), else one per return.
        if len(line.expandtabs(4)) <= 120:
            lines.append(line)
        else:
            lines += [f'\t["{name}"] = {{', *(f"\t\t{value}," for value in values), "\t},"]
    return "\n".join(lines + ["}", ""])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--annotations", type=Path, required=True)
    parser.add_argument("--ui", type=Path, required=True)
    args = parser.parse_args()
    returns = read(args.annotations, args.ui)
    OUTPUT.write_text(render(returns))
    print(f"{len(returns)} undocumented functions -> {OUTPUT}")


if __name__ == "__main__":
    main()
