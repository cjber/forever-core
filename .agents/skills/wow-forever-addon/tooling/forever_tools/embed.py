"""Embed the pinned ForeverCore in a consumer's package, so the addon runs with or without the standalone addon.

    python3 -m tools.forever_tools.embed [--core DIR] [ROOT]

Run it on a disposable checkout right before the packager (the CI package job, the Release workflow and
`forever_client.py build-dev`): it rewrites the checkout in place. It does nothing unless the root TOC opts in with
`## X-Forever-Core-Embed: 1`, so every consumer's workflows can call it.

What it writes:

- `Libs/ForeverCore/`: the schema-1 copy that core's own `tools/build_embedded_core.py` plans from the pinned
  checkout (`--core`, else `$FOREVER_CORE`, else `forever-core/`) at the version `tools/forever-core.txt` names.
  The producer is loaded from that checkout, never from this file, so every consumer on one pin ships byte-equal
  copies with one digest, and the loader elects any of them.
- Every consumer Lua file the TOC loads, directly or through an XML `Script`, wrapped as one deferred chunk. The
  wrapper sits on the file's first line, so error line numbers stay the source's. Without the registry that
  `ForeverCoreHost.lua` sets up (a spec loading the file on its own), the wrapper runs the file at once, as before.
- `ForeverCoreRun.lua`, after the consumer's files, runs the chunks in TOC order once ForeverCore is ready. With the
  standalone addon installed that is inline, during the addon's own file load, exactly when the files ran before.
  Without it the elected copy boots at PLAYER_LOGIN; the chunks run then, and each frame they registered gets the
  addon's own ADDON_LOADED and the PLAYER_LOGIN it missed.
- The root TOC: the copy's files first, then `ForeverCoreHost.lua`, the consumer's files in their order,
  `ForeverCoreRun.lua` and the producer's `ForeverCoreReady.lua` last.

The consumer's TOC must name ForeverCore under `OptionalDeps`, never `Dependencies`: a required dependency keeps the
client from loading the addon once the standalone is gone, which is what the embedded copy is for.
"""

import argparse
import hashlib
import importlib.util
import json
import os
import posixpath
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path, PurePosixPath

from . import core_pin

__all__ = ["EMBED_FIELD", "EmbedError", "enabled", "main", "transform", "wrap"]

EMBED_FIELD = core_pin.EMBED_FIELD
PREFIX = "Libs/ForeverCore/"
HOST_BEGIN = "ForeverCoreHost.lua"
HOST_RUN = "ForeverCoreRun.lua"
READY = "ForeverCoreReady.lua"
PIN_PATH = "tools/forever-core.txt"
BOM = b"\xef\xbb\xbf"
LOAD_TAGS = {"Include", "Script"}

# The deferred wrapper. The header ends without a newline so the source's first line stays line 1; the footer
# registers the chunk under an embedded TOC, or runs it now (returning its values) when no registry exists.
HEADER = b"local ForeverCoreHostChunk = function(...) "
FOOTER = (
    b"\nend local _, ForeverCoreHostNs = ... "
    b'if type(ForeverCoreHostNs) == "table" and type(ForeverCoreHostNs.ForeverCoreHostChunks) == "table" then '
    b"local chunks = ForeverCoreHostNs.ForeverCoreHostChunks chunks[#chunks + 1] = ForeverCoreHostChunk "
    b"else return ForeverCoreHostChunk(...) end\n"
)

BEGIN_SOURCE = b"""-- Generated by forever_tools.embed. The wrapped files register here; ForeverCoreRun.lua runs them.
local _, host = ...
host.ForeverCoreHostChunks = {}
"""

RUN_SOURCE = b"""-- Generated by forever_tools.embed. Runs the addon's files, in TOC order, once ForeverCore is ready.
-- With the standalone ForeverCore loaded the loader is already active, so OnReady calls back at once, inside this
-- file's load: the files run exactly where they always did. Otherwise the elected copy boots at PLAYER_LOGIN and the
-- files run then; each frame they registered gets this addon's ADDON_LOADED and the PLAYER_LOGIN it missed.
local addon, host = ...
local chunks = host.ForeverCoreHostChunks or {}
host.ForeverCoreHostChunks = nil

local function Report(message)
	local handler = geterrorhandler and geterrorhandler()
	if handler then
		return handler(message)
	end
	return message
end

local REPLAYED = { "ADDON_LOADED", "PLAYER_LOGIN" }

local function Registered(event)
	local set = {}
	if GetFramesRegisteredForEvent then
		for _, frame in ipairs({ GetFramesRegisteredForEvent(event) }) do
			set[frame] = true
		end
	end
	return set
end

local inline = true
ForeverCoreLoader.OnReady(function()
	local before = {}
	if not inline then
		for _, event in ipairs(REPLAYED) do
			before[event] = Registered(event)
		end
	end
	-- One file's error stops that file only, as the client's own file loading does.
	for index = 1, #chunks do
		xpcall(function()
			return chunks[index](addon, host)
		end, Report)
	end
	if inline then
		return
	end
	for _, event in ipairs(REPLAYED) do
		for frame in pairs(Registered(event)) do
			if not before[event][frame] then
				if event == "PLAYER_LOGIN" then
					-- PLAYER_LOGIN is still dispatching; a frame added during it gets this one call, never a second.
					frame:UnregisterEvent(event)
				end
				local script = frame:GetScript("OnEvent")
				if script then
					xpcall(function()
						return script(frame, event, event == "ADDON_LOADED" and addon or nil)
					end, Report)
				end
			end
		end
	end
end)
inline = false
"""


class EmbedError(ValueError):
    """The checkout cannot be embedded as it stands; the message says what to change."""


def _toc_path(root: Path) -> Path:
    """The root TOC the packager ships, resolved by `core_pin.toc_name_for` as every checker resolves it."""
    policy = core_pin.policy_path(root)
    try:
        package = core_pin.policy_package(policy.read_text(encoding="utf-8", errors="replace") if policy else "")
        name = core_pin.toc_name_for(package, [path.name for path in root.glob("*.toc")])
    except ValueError as error:
        raise EmbedError(f"{root}: {error}") from None
    if name is None or not (root / name).is_file():
        raise EmbedError(f"{root}: no root TOC {name or '(none found)'}")
    return root / name


_fields = core_pin.toc_fields


def enabled(root: Path) -> bool:
    """True when the root TOC opts in with `## X-Forever-Core-Embed: 1` (`core_pin.embeds`).

    An opt-in line with any other value is an error, not a quiet "no": a consumer that meant to embed would otherwise
    ship without its copy.
    """
    toc_path = _toc_path(root)
    toc_text = toc_path.read_text(encoding="utf-8-sig")
    problem = core_pin.embed_problem(toc_text, toc_path.name)
    if problem:
        raise EmbedError(problem)
    return core_pin.embeds(toc_text)


def wrap(data: bytes) -> bytes:
    """One consumer file as a deferred chunk, its first line still line 1."""
    bom = data.startswith(BOM)
    body = data[len(BOM) :] if bom else data
    if body.startswith(b"#"):
        raise EmbedError("a file starting with # cannot be wrapped")
    return (BOM if bom else b"") + HEADER + body + FOOTER


def _builder(core: Path):
    path = core / "tools" / "build_embedded_core.py"
    if not path.is_file():
        raise EmbedError(f"{path}: missing; the pinned ForeverCore checkout has no embedded producer")
    spec = importlib.util.spec_from_file_location("forever_core_build_embedded", path)
    if spec is None or spec.loader is None:
        raise EmbedError(f"{path}: cannot be loaded as a module")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _loads(toc_text: str) -> list[str]:
    return [
        line.strip().replace("\\", "/")
        for line in toc_text.splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]


def _lua_graph(root: Path, loads: list[str]) -> list[str]:
    """Every Lua file the TOC loads, in load order, through XML Script and Include tags."""
    seen: set[str] = set()
    lua: list[str] = []

    def visit(name: str, by: str) -> None:
        path = PurePosixPath(name)
        if any(part in ("", "..") for part in path.parts) or name.startswith("/"):
            raise EmbedError(f"{by}: loads {name}, outside the addon")
        key = name.casefold()
        if key in seen:
            raise EmbedError(f"{by}: loads {name} a second time")
        seen.add(key)
        if not (root / name).is_file():
            raise EmbedError(f"{by}: loads {name}, which is not in the checkout")
        if key.startswith(PREFIX.casefold()) or PurePosixPath(key).name in {
            HOST_BEGIN.casefold(),
            HOST_RUN.casefold(),
            READY.casefold(),
        }:
            raise EmbedError(f"{by}: loads {name}, a name the embedded copy owns")
        suffix = path.suffix.lower()
        if suffix == ".lua":
            lua.append(name)
        elif suffix == ".xml":
            for element in ET.parse(root / name).iter():
                if element.tag.rsplit("}", 1)[-1] in LOAD_TAGS and "file" in element.attrib:
                    target = element.attrib["file"].replace("\\", "/")
                    if target.lower().startswith("interface/"):
                        raise EmbedError(f"{name}: loads {target} by client path; name it relative to the XML")
                    visit(posixpath.normpath(posixpath.join(posixpath.dirname(name), target)), name)
        else:
            raise EmbedError(f"{by}: loads {name}, which is neither Lua nor XML")

    for name in loads:
        visit(name, "TOC")
    return lua


def transform(root: Path, core: Path, version: str) -> dict[str, object]:
    """Rewrite the consumer checkout at `root` in place; return what was written."""
    toc_path = _toc_path(root)
    folder = toc_path.stem
    toc_text = toc_path.read_text(encoding="utf-8-sig")
    fields = _fields(toc_text)
    if not core_pin.embeds(toc_text):
        raise EmbedError(f"{toc_path.name}: no `## {EMBED_FIELD}: 1`; nothing to embed")
    others = sorted(path.name for path in root.glob("*.toc") if path.name != toc_path.name)
    if others:
        raise EmbedError(
            f"{toc_path.name}: the embed step rewrites one root TOC, but the checkout also has {', '.join(others)};"
            " an addon loaded from another TOC would run without its core"
        )
    dependencies = {
        name.strip()
        for name in re.split(r"[,\s]+", fields.get("dependencies", "") + " " + fields.get("requireddeps", ""))
    }
    if "ForeverCore" in dependencies:
        raise EmbedError(f"{toc_path.name}: ForeverCore is a required dependency; move it to ## OptionalDeps")
    saved = [name.strip() for name in fields.get("savedvariables", "").split(",") if name.strip()]
    if not saved:
        scope = (
            " (## SavedVariablesPerCharacter is saved per character; core's store is account-wide)"
            if "savedvariablespercharacter" in fields
            else ""
        )
        raise EmbedError(
            f"{toc_path.name}: no ## SavedVariables{scope}; the embedded copy mirrors core's account store into one"
            " account global, so add one"
        )
    if len(saved) > 1:
        raise EmbedError(
            f"{toc_path.name}: ## SavedVariables lists {', '.join(saved)}; the embedded copy mirrors core's store into"
            " one account global, and which one cannot be told from the TOC, so list exactly one"
        )
    if (root / PREFIX).exists():
        raise EmbedError(f"{PREFIX}: already in the checkout; embed runs once, on a fresh checkout")
    builder = _builder(core)
    planned = builder.plan(core, folder, version, saved[0], b"")
    core_files = {name: data for name, data in planned.items() if name.startswith(PREFIX) or name == READY}
    core_loads = _loads(planned[folder + ".toc"].decode())
    if not core_loads or core_loads[-1] != READY:
        raise EmbedError("the pinned producer's TOC does not end with ForeverCoreReady.lua")
    loads = _loads(toc_text)
    lua = _lua_graph(root, loads)
    for name in (HOST_BEGIN, HOST_RUN, READY):
        if (root / name).exists():
            raise EmbedError(f"{name}: already in the checkout; the embedded copy owns that name")
    for name in lua:
        (root / name).write_bytes(wrap((root / name).read_bytes()))
    for name, data in core_files.items():
        target = root / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    (root / HOST_BEGIN).write_bytes(BEGIN_SOURCE)
    (root / HOST_RUN).write_bytes(RUN_SOURCE)
    headers = [line for line in toc_text.splitlines() if line.startswith("##")]
    order = core_loads[:-1] + [HOST_BEGIN] + loads + [HOST_RUN, READY]
    toc_path.write_text(
        "\n".join(headers) + "\n\n" + "\n".join(name.replace("/", "\\") for name in order) + "\n", encoding="utf-8"
    )
    manifest = json.loads(core_files[PREFIX + "bundle.json"])
    manifest["files"] = {
        name: hashlib.sha256(data).hexdigest()
        for name, data in sorted(core_files.items())
        if not name.endswith(".json")
    }
    manifest["wrapped"] = lua
    (root / PREFIX / "bundle.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    _stage(root, [PREFIX, HOST_BEGIN, HOST_RUN, READY])
    return {"folder": folder, "build": manifest["build"], "digest": manifest["source_digest"], "wrapped": len(lua)}


def _stage(root: Path, names: list[str]) -> None:
    """Stage the new files when `root` is a git checkout. The BigWigs packager adds every file `git ls-files --others`
    lists to its ignore list, so an untracked `Libs/ForeverCore/` would be left out of the zip while the rewritten
    TOC still loads it. A plain folder (`build-dev`'s git archive) has nothing to stage."""
    inside = subprocess.run(
        ["git", "-C", str(root), "rev-parse", "--is-inside-work-tree"], capture_output=True, text=True, check=False
    )
    if inside.returncode or inside.stdout.strip() != "true":
        return
    staged = subprocess.run(
        ["git", "-C", str(root), "add", "--force", "--", *names], capture_output=True, text=True, check=False
    )
    if staged.returncode:
        raise EmbedError(f"git add of the embedded files failed: {staged.stderr.strip()}")


def pinned_version(root: Path) -> str:
    text = (root / PIN_PATH).read_text().strip()
    if not re.fullmatch(r"v\d+\.\d+\.\d+", text):
        raise EmbedError(f"{PIN_PATH}: {text!r} is not a release tag such as v1.14.5")
    return text[1:]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("root", nargs="?", type=Path, default=Path.cwd())
    parser.add_argument(
        "--core", type=Path, help="pinned ForeverCore checkout (default $FOREVER_CORE, else forever-core/)"
    )
    args = parser.parse_args(argv)
    root = args.root
    try:
        if not enabled(root):
            print(f"embed: {_toc_path(root).name} does not set ## {EMBED_FIELD}: 1; nothing to do")
            return 0
        core = args.core or Path(os.environ.get("FOREVER_CORE") or root / "forever-core")
        result = transform(root, core, pinned_version(root))
    except (EmbedError, OSError, ET.ParseError) as error:
        print(f"embed: {error}", file=sys.stderr)
        return 1
    print(
        f"embed: {result['folder']} carries ForeverCore build {result['build']} ({str(result['digest'])[:12]}), "
        f"{result['wrapped']} files deferred"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
