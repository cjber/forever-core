"""Specs for tools/devsmoke/eval.py: the snippet compiler, the generated Inbox addon and the AddOns link."""

from __future__ import annotations

import contextlib
import importlib.util
import io
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

SPEC = importlib.util.spec_from_file_location("devsmoke_eval", Path(__file__).parent / "devsmoke/eval.py")
ev = importlib.util.module_from_spec(SPEC)
sys.modules["devsmoke_eval"] = ev
SPEC.loader.exec_module(ev)


class DevSmokeEvalTest(unittest.TestCase):
    def setUp(self):
        self.root = Path(self.enterContext(tempfile.TemporaryDirectory()))
        self.addons = self.root / "client/Interface/AddOns"
        self.addons.mkdir(parents=True)
        self.checkout = self.root / "checkout"
        self.addon = self.checkout / "tools/devsmoke/!!DevSmoke"
        self.addon.mkdir(parents=True)
        (self.checkout / ".git").mkdir()
        (self.addon / "!!DevSmoke.toc").write_text("## Interface: 16001\n## Title: Dev Smoke\nCore.lua\n")
        (self.addon / "Core.lua").write_text("")
        (self.addons / "!!DevSmoke").symlink_to(self.addon)
        self.snippet = self.root / "probe.lua"
        self.snippet.write_text('print("hi")\nreturn 42\n')
        self.run = self.enterContext(
            mock.patch.object(ev.subprocess, "run", return_value=mock.Mock(returncode=0, stdout="", stderr=""))
        )
        self.which = self.enterContext(
            mock.patch.object(
                ev.shutil,
                "which",
                side_effect=lambda name: f"/usr/bin/{name}" if name in ("luajit", "luac5.1") else None,
            )
        )

    def test_writes_the_chunk_and_links_the_inbox(self):
        result = ev.write_snippet(self.snippet, self.addons)
        inbox = self.addon / "!!DevSmokeInbox"
        chunk = inbox / "Eval.lua"
        self.assertEqual(result["chunk"], chunk)
        text = chunk.read_text()
        self.assertTrue(
            text.startswith("DevSmokeEval = function(...) -- generated by tools/devsmoke/eval.py from probe.lua")
        )
        self.assertEqual(text.splitlines()[1], 'print("hi")', "the snippet is copied verbatim after the wrapper")
        self.assertTrue(text.endswith("\nend\n"))
        toc = (inbox / "!!DevSmokeInbox.toc").read_text()
        self.assertIn("## LoadOnDemand: 1", toc)
        self.assertIn("probe.lua", toc)
        self.assertTrue(toc.endswith("Eval.lua\n"))
        link = self.addons / "!!DevSmokeInbox"
        self.assertTrue(link.is_symlink())
        self.assertEqual(link.resolve(), inbox.resolve())
        self.assertEqual(result["lines"], 2)
        self.assertEqual(
            [call.args[0][:2] for call in self.run.call_args_list],
            [["/usr/bin/luajit", "-bl"], ["/usr/bin/luac5.1", "-p"]],
            "both compilers that are installed check the snippet",
        )

    def test_only_luajit_is_needed_when_luac_is_absent(self):
        self.which.side_effect = lambda name: "/usr/bin/luajit" if name == "luajit" else None
        ev.write_snippet(self.snippet, self.addons)
        self.assertEqual([call.args[0][:2] for call in self.run.call_args_list], [["/usr/bin/luajit", "-bl"]])

    def test_a_parse_error_is_refused_before_anything_is_written(self):
        self.run.return_value = mock.Mock(returncode=1, stdout="", stderr="probe.lua:2: 'end' expected")
        with self.assertRaisesRegex(ev.EvalError, "probe.lua:2: 'end' expected"):
            ev.write_snippet(self.snippet, self.addons)
        self.assertFalse(
            (self.addon / "!!DevSmokeInbox").exists(), "no inbox is written for a snippet that does not parse"
        )
        self.assertFalse((self.addons / "!!DevSmokeInbox").exists())

    def test_no_compiler_on_path_is_refused(self):
        self.which.side_effect = lambda name: None
        with self.assertRaisesRegex(ev.EvalError, "no Lua compiler"):
            ev.write_snippet(self.snippet, self.addons)

    def test_the_addons_link_must_be_a_symlink_into_a_checkout(self):
        link = self.addons / "!!DevSmoke"
        link.unlink()
        link.mkdir()
        with self.assertRaisesRegex(ev.EvalError, "is not a symlink"):
            ev.addon_folder(self.addons)

        link.rmdir()
        elsewhere = self.root / "elsewhere"
        elsewhere.mkdir()
        link.symlink_to(elsewhere)
        with self.assertRaisesRegex(ev.EvalError, "does not point into a checkout"):
            ev.addon_folder(self.addons)

        (self.addon / "!!DevSmoke.toc").write_text("## Interface: 16001\nCore.lua\n")
        link.unlink()
        link.symlink_to(self.addon)
        with self.assertRaisesRegex(ev.EvalError, "does not point into a checkout"):
            ev.addon_folder(self.addons)

    def test_a_checkout_outside_git_is_refused(self):
        (self.checkout / ".git").rmdir()
        with self.assertRaisesRegex(ev.EvalError, "not inside a git checkout"):
            ev.addon_folder(self.addons)

    def test_a_real_inbox_directory_is_never_replaced(self):
        (self.addons / "!!DevSmokeInbox").mkdir()
        with self.assertRaisesRegex(ev.EvalError, "is not a symlink"):
            ev.write_snippet(self.snippet, self.addons)

    def test_a_stale_inbox_link_is_repointed(self):
        stale = self.root / "stale-inbox"
        stale.mkdir()
        (self.addons / "!!DevSmokeInbox").symlink_to(stale)
        ev.write_snippet(self.snippet, self.addons)
        self.assertEqual((self.addons / "!!DevSmokeInbox").resolve(), (self.addon / "!!DevSmokeInbox").resolve())

    def test_cli_prints_the_next_step(self):
        with (
            mock.patch.object(ev, "default_addons", return_value=self.addons),
            contextlib.redirect_stdout(io.StringIO()) as out,
        ):
            self.assertEqual(ev.main([str(self.snippet)]), 0)
        printed = out.getvalue()
        self.assertIn("wrote", printed)
        self.assertIn("next: /reload, then read DevSmokeDB.eval", printed)

    def test_cli_refuses_a_missing_file(self):
        with contextlib.redirect_stderr(io.StringIO()) as err:
            self.assertEqual(ev.main([str(self.root / "missing.lua")]), 2)
        self.assertIn("is not a file", err.getvalue())


if __name__ == "__main__":
    unittest.main()
