"""Specs for tools/devsmoke/eval.py: the snippet compiler, the generated Inbox addon and the AddOns link."""

from __future__ import annotations

import contextlib
import importlib.util
import io
import re
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

SPEC = importlib.util.spec_from_file_location("devsmoke_eval", Path(__file__).parent / "devsmoke/eval.py")
ev = importlib.util.module_from_spec(SPEC)
sys.modules["devsmoke_eval"] = ev
SPEC.loader.exec_module(ev)


class DevSmokeEvalTest(unittest.TestCase):
    def setUp(self):
        self.root = Path(self.enterContext(tempfile.TemporaryDirectory()))
        self.addons = self.root / "client/Interface/AddOns"
        self.addons.mkdir(parents=True)
        self.checkout = self.root / "checkout"
        self.addon = self.checkout / "tools/devsmoke/!!DevSmoke"
        self.addon.mkdir(parents=True)
        (self.checkout / ".git").mkdir()
        (self.addon / "!!DevSmoke.toc").write_text(
            "## Interface: 16001\n## Title: Dev Smoke\n## X-DevSmoke-Capture-Protocol: 1\nCore.lua\n"
        )
        (self.addon / "Core.lua").write_text("")
        (self.addons / "!!DevSmoke").symlink_to(self.addon)
        self.snippet = self.root / "probe.lua"
        self.snippet.write_text('print("hi")\nreturn 42\n')
        self.run = self.enterContext(
            mock.patch.object(ev.subprocess, "run", return_value=mock.Mock(returncode=0, stdout="", stderr=""))
        )
        self.which = self.enterContext(
            mock.patch.object(
                ev.shutil,
                "which",
                side_effect=lambda name: f"/usr/bin/{name}" if name in ("luajit", "luac5.1") else None,
            )
        )

    def test_writes_the_chunk_and_links_the_inbox(self):
        result = ev.write_snippet(self.snippet, self.addons)
        inbox = self.addon / "!!DevSmokeInbox"
        chunk = inbox / "Eval.lua"
        self.assertEqual(result["chunk"], chunk)
        text = chunk.read_text()
        header = text.splitlines()[0]
        self.assertRegex(header, r'^DevSmokeEvalRun = "[0-9a-f]{16}"; ')
        self.assertEqual(
            header,
            f'DevSmokeEvalRun = "{result["token"]}"; DevSmokeEvalCapture = true; DevSmokeEval = function(...) '
            "-- generated by tools/devsmoke/eval.py from probe.lua; do not edit",
        )
        self.assertEqual(text.splitlines()[1], 'print("hi")', "the snippet is copied verbatim after the wrapper")
        self.assertTrue(text.endswith("\nend\n"))
        toc = (inbox / "!!DevSmokeInbox.toc").read_text()
        self.assertIn("## LoadOnDemand: 1", toc)
        self.assertIn("probe.lua", toc)
        self.assertTrue(toc.endswith("Eval.lua\n"))
        link = self.addons / "!!DevSmokeInbox"
        self.assertTrue(link.is_symlink())
        self.assertEqual(link.resolve(), inbox.resolve())
        self.assertEqual(result["lines"], 2)
        self.assertEqual(
            [call.args[0][:2] for call in self.run.call_args_list],
            [["/usr/bin/luajit", "-bl"], ["/usr/bin/luac5.1", "-p"]],
            "both compilers that are installed check the snippet",
        )

    def test_an_eval_chunk_can_turn_off_the_proof_ready_screenshot(self):
        # `forever_client.py eval` reloads twice to save its own result; a delayed flow screenshot would race that
        # second reload, so its chunk says it is not a proof flow (#588).
        ev.write_snippet(self.snippet, self.addons, capture=False)
        chunk = (self.addon / "!!DevSmokeInbox/Eval.lua").read_text()
        self.assertIn("DevSmokeEvalCapture = false;", chunk.splitlines()[0])

    def test_a_slash_flow_runs_through_the_clients_chat_parser(self):
        # A slash proof flow goes through the same reported route as a Lua flow, so its capture follows a confirmed
        # run rather than a fixed pause (#573).
        result = ev.write_slash("/lf", self.addons)
        chunk = (self.addon / "!!DevSmokeInbox/Eval.lua").read_text()
        self.assertIn("DevSmokeEvalCapture = true;", chunk.splitlines()[0])
        self.assertIn('edit:SetText("/lf")', chunk)
        self.assertIn("ChatEdit_SendText(edit)", chunk)
        self.assertIn("return function()", chunk)
        self.assertEqual(result["snippet"], Path("/lf"))
        self.assertTrue(result["token"])

    def test_a_slash_flow_is_quoted_as_one_lua_string(self):
        source = ev.slash_source('/say "hi"\\there')
        self.assertIn('edit:SetText("/say \\"hi\\"\\\\there")', source)
        self.assertNotIn("\n\nthere", source, "the command cannot become a second statement")

    def test_slash_waits_for_registration_sends_once_and_names_missing_command(self):
        script = (
            """
local now, sends = 0, 0
GetTime = function() return now end
SlashCmdList = {}
ChatFrame1EditBox = {SetText=function(self, text) self.text=text end,
    GetText=function(self) return self.text or '' end}
ChatEdit_SendText = function(edit) sends=sends+1; edit.text='' end
local function snippet()
"""
            + ev.slash_source("/lf")
            + """
end
local ready = snippet()
assert(sends == 0 and not ready(), 'wait for later PLAYER_LOGIN handlers')
SlashCmdList.LEGACY = function() end
SLASH_LEGACY1 = '/lfoo'
assert(not ready(), 'match exact word')
SLASH_LEGACY2 = '/lf'
assert(ready() and ready() and sends == 1, 'send exactly once inside ready')
SlashCmdList = {}
local missing = snippet()
now = 56
local ok, err = pcall(missing)
assert(not ok and err:find('slash command never registered: /lf', 1, true))
now = 0
hash_SlashCmdList = {['/LF'] = function() end}
assert(snippet()(), 'cached parser commands work')
"""
        )
        process = subprocess.Popen(
            ["luajit", "-"], stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True
        )
        _out, err = process.communicate(script)
        self.assertEqual(process.returncode, 0, err)

    def test_slash_deadline_precedes_flow_ready_timeout(self):
        core = (ev.TOOLS / "devsmoke/!!DevSmoke/Core.lua").read_text()
        limit = int(re.search(r"local FLOW_READY_LIMIT = (\d+)", core)[1])
        self.assertLess(ev.SLASH_READY_LIMIT, limit)
        self.assertIn(f"GetTime() - started >= {ev.SLASH_READY_LIMIT}", ev.slash_source("/lf"))

    def test_generated_builtin_commands_match_client_allowlist(self):
        commands = set(re.findall(r"word == '([^']+)'", ev.slash_source("/lf")))
        self.assertEqual(commands, ev.client().UI_COMMANDS)

    def test_builtin_proof_commands_do_not_wait_for_addon_registration(self):
        script = (
            "SlashCmdList = {}; GetTime=function() return 0 end; "
            + "ChatFrame1EditBox={SetText=function() end, GetText=function() return '' end}; "
            + "ChatEdit_SendText=function() end; local function snippet()\n"
            + ev.slash_source("/reload")
            + "end; assert(snippet()())"
        )
        process = subprocess.Popen(
            ["luajit", "-"], stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True
        )
        _out, err = process.communicate(script)
        self.assertEqual(process.returncode, 0, err)

    def test_every_write_stamps_its_own_run_token(self):
        # A reader only has the SavedVariables file, which holds the previous session until the next reload, so each
        # write's chunk has to say which run its result belongs to (#580).
        first = ev.write_snippet(self.snippet, self.addons)["token"]
        second = ev.write_snippet(self.snippet, self.addons)["token"]
        self.assertNotEqual(first, second, "a write's token is its own")
        chunk = (self.addon / "!!DevSmokeInbox/Eval.lua").read_text()
        self.assertTrue(chunk.startswith(f'DevSmokeEvalRun = "{second}"; '), chunk.splitlines()[0])
        self.assertNotIn('"' + first + '"', chunk, "the previous write's token is gone with its chunk")

    def test_only_luajit_is_needed_when_luac_is_absent(self):
        self.which.side_effect = lambda name: "/usr/bin/luajit" if name == "luajit" else None
        ev.write_snippet(self.snippet, self.addons)
        self.assertEqual([call.args[0][:2] for call in self.run.call_args_list], [["/usr/bin/luajit", "-bl"]])

    def test_a_parse_error_is_refused_before_anything_is_written(self):
        self.run.return_value = mock.Mock(returncode=1, stdout="", stderr="probe.lua:2: 'end' expected")
        with self.assertRaisesRegex(ev.EvalError, "probe.lua:2: 'end' expected"):
            ev.write_snippet(self.snippet, self.addons)
        self.assertFalse(
            (self.addon / "!!DevSmokeInbox").exists(), "no inbox is written for a snippet that does not parse"
        )
        self.assertFalse((self.addons / "!!DevSmokeInbox").exists())

    def test_no_compiler_on_path_is_refused(self):
        self.which.side_effect = lambda name: None
        with self.assertRaisesRegex(ev.EvalError, "no Lua compiler"):
            ev.write_snippet(self.snippet, self.addons)

    def test_the_addons_link_must_be_a_symlink_into_a_checkout(self):
        link = self.addons / "!!DevSmoke"
        link.unlink()
        link.mkdir()
        with self.assertRaisesRegex(ev.EvalError, "is not a symlink"):
            ev.addon_folder(self.addons)

        link.rmdir()
        elsewhere = self.root / "elsewhere"
        elsewhere.mkdir()
        link.symlink_to(elsewhere)
        with self.assertRaisesRegex(ev.EvalError, "does not point into a checkout"):
            ev.addon_folder(self.addons)

        (self.addon / "!!DevSmoke.toc").write_text("## Interface: 16001\nCore.lua\n")
        link.unlink()
        link.symlink_to(self.addon)
        with self.assertRaisesRegex(ev.EvalError, "does not point into a checkout"):
            ev.addon_folder(self.addons)

    def test_an_old_devsmoke_checkout_fails_before_writing_an_inbox(self):
        (self.addon / "!!DevSmoke.toc").write_text("## Interface: 16001\n## Title: Dev Smoke\nCore.lua\n")
        with self.assertRaisesRegex(ev.EvalError, "does not provide capture protocol 1"):
            ev.write_snippet(self.snippet, self.addons)
        self.assertFalse((self.addon / "!!DevSmokeInbox").exists())
        self.assertFalse((self.addons / "!!DevSmokeInbox").exists())

    def test_a_checkout_outside_git_is_refused(self):
        (self.checkout / ".git").rmdir()
        with self.assertRaisesRegex(ev.EvalError, "not inside a git checkout"):
            ev.addon_folder(self.addons)

    def test_a_real_inbox_directory_is_never_replaced(self):
        (self.addons / "!!DevSmokeInbox").mkdir()
        with self.assertRaisesRegex(ev.EvalError, "is not a symlink"):
            ev.write_snippet(self.snippet, self.addons)

    def test_a_stale_inbox_link_is_repointed(self):
        stale = self.root / "stale-inbox"
        stale.mkdir()
        (self.addons / "!!DevSmokeInbox").symlink_to(stale)
        ev.write_snippet(self.snippet, self.addons)
        self.assertEqual((self.addons / "!!DevSmokeInbox").resolve(), (self.addon / "!!DevSmokeInbox").resolve())

    def test_clearing_removes_the_generated_chunk_toc_and_link(self):
        ev.write_snippet(self.snippet, self.addons)
        inbox = self.addon / "!!DevSmokeInbox"
        link = self.addons / "!!DevSmokeInbox"
        removed = ev.clear_inbox(self.addons)
        self.assertEqual(
            set(removed),
            {link, inbox / "Eval.lua", inbox / "!!DevSmokeInbox.toc", inbox},
        )
        self.assertFalse(link.is_symlink(), "the AddOns link is gone, so a later login loads no inbox")
        self.assertFalse(inbox.exists(), "the generated inbox is gone with its chunk")

    def test_clearing_an_inbox_that_is_already_gone_is_not_an_error(self):
        self.assertEqual(ev.clear_inbox(self.addons), ())

    def test_clearing_a_stale_link_leaves_its_target_alone(self):
        stale = self.root / "stale-inbox"
        stale.mkdir()
        marker = stale / "keep.txt"
        marker.write_text("not ours")
        (self.addons / "!!DevSmokeInbox").symlink_to(stale)
        removed = ev.clear_inbox(self.addons)
        self.assertEqual(removed, (self.addons / "!!DevSmokeInbox",))
        self.assertFalse((self.addons / "!!DevSmokeInbox").is_symlink())
        self.assertTrue(marker.exists(), "a link to another folder is removed, never emptied")

    def test_clearing_never_deletes_a_real_inbox_folder(self):
        entry = self.addons / "!!DevSmokeInbox"
        entry.mkdir()
        marker = entry / "keep.txt"
        marker.write_text("not ours")
        self.assertEqual(ev.clear_inbox(self.addons), ())
        self.assertTrue(marker.exists())

    def test_cli_prints_the_next_step(self):
        with (
            mock.patch.object(ev, "default_addons", return_value=self.addons),
            contextlib.redirect_stdout(io.StringIO()) as out,
        ):
            self.assertEqual(ev.main([str(self.snippet)]), 0)
        printed = out.getvalue()
        self.assertIn("wrote", printed)
        self.assertIn("next: /reload, then read DevSmokeDB.eval", printed)

    def test_cli_refuses_a_missing_file(self):
        with contextlib.redirect_stderr(io.StringIO()) as err:
            self.assertEqual(ev.main([str(self.root / "missing.lua")]), 2)
        self.assertIn("is not a file", err.getvalue())


if __name__ == "__main__":
    unittest.main()
