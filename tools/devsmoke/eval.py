#!/usr/bin/env python3
"""Load a Lua snippet into the linked !!DevSmoke dev addon and keep its output in DevSmokeDB.eval.

A chat `/run` line is cut at 255 characters, so anything longer reaches Lua as half a statement and buries BugGrabber
in parse errors. This tool takes a file instead: it compiles FILE first (`luajit -bl`, and `luac5.1 -p` when it is
installed) so a parse error is refused before any reload, wraps it as the `DevSmokeEval` chunk, and writes it into the
gitignored `!!DevSmokeInbox` folder inside the !!DevSmoke checkout the client's AddOns link points at. That folder is
linked into AddOns as the load-on-demand addon of the same name, whose `Eval.lua` the client runs.

The generated `Eval.lua` is one wrapper line, the snippet verbatim, and the closing `end`:

    DevSmokeEvalRun = "TOKEN"; DevSmokeEval = function(...) -- generated by tools/devsmoke/eval.py; do not edit
    <the snippet, unchanged>
    end

The snippet's line 1 is the generated file's line 2, so an error naming `Eval.lua:6` is its line 5. !!DevSmoke runs
the chunk under `xpcall` at login and on `/devsmoke eval`: what it prints and every value it returns go to the Agent
tab in lines under 255 characters, and the same lines land in `DevSmokeDB.eval.out`, with `err` holding the error and
its stack. Nothing reaches BugGrabber.

`TOKEN` is a fresh run token for every write, which !!DevSmoke copies into `DevSmokeDB.eval.run`. SavedVariables reach
disk only at the next reload or logout, so the file a reader opens still holds an earlier session's eval: the token is
how a reader tells the result this snippet wrote from the one before it (#580).

The Inbox is its own add-on folder because the client runs only files a TOC names: pointing `!!DevSmoke` itself at
the snippet would log `Couldn't open` for every fresh checkout that has not written one yet, and git cannot hide the
changes to a tracked file. Nothing exists for the client to miss until the first eval writes the folder.

The client reads the inbox once per session: the first `/devsmoke eval` or login in a session loads it, and any
snippet written later needs `/reload`. `forever_client.py eval` writes the file and reloads, so it always runs the
snippet it just wrote, and reloads once more so the result it reads is that snippet's own. A proof, smoke or eval
session calls `clear_inbox` when it ends, including when it fails, so no later login runs the snippet it left (#589).

    tools/devsmoke/eval.py FILE
    tools/headless/forever_client.py eval FILE    # the same, then /reload and the saved DevSmokeDB.eval

At the client: /reload, then read DevSmokeDB.eval, or the Agent chat tab, which shows the same lines.
"""

from __future__ import annotations

import argparse
import secrets
import shutil
import subprocess
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parents[1]
ADDON = "!!DevSmoke"
INBOX = "!!DevSmokeInbox"
TOC_TITLE = "## Title: Dev Smoke"
CHUNK = "Eval.lua"
# The global the generated chunk carries this write's run token in, which !!DevSmoke copies into DevSmokeDB.eval.run.
TOKEN = "DevSmokeEvalRun"


class EvalError(Exception):
    """A refusal the agent should read: printed without a traceback, exit status 2."""


def client():
    """forever_client, which already knows the client's paths, loaded from tools/headless on first use."""
    module = sys.modules.get("forever_client")
    if module is None:
        sys.path.insert(0, str(TOOLS / "headless"))
        import forever_client

        module = forever_client
    return module


def default_addons() -> Path:
    """The client AddOns folder forever_client.py already knows how to find."""
    return client().CLIENT / "Interface/AddOns"


def addon_folder(addons: Path) -> Path:
    """The checkout folder behind AddOns/!!DevSmoke, refusing anything that is not a link into a checkout of it."""
    link = addons / ADDON
    if not link.is_symlink():
        raise EvalError(
            f"{link} is not a symlink: link {ADDON} from a forever-core checkout into the client's AddOns first"
        )
    target = link.resolve()
    toc = target / f"{ADDON}.toc"
    try:
        titled = toc.is_file() and TOC_TITLE in toc.read_text(encoding="utf-8", errors="replace")
    except OSError:
        titled = False
    if not target.is_dir() or not titled:
        raise EvalError(f"{link} does not point into a checkout of {ADDON}")
    if not any((parent / ".git").exists() for parent in (target, *target.parents)):
        raise EvalError(f"{target} is not inside a git checkout: eval refuses to leave a snippet there")
    return target


def check_source(path: Path) -> None:
    """Compile the snippet with every compiler on PATH, so a parse error fails before the reload."""
    if not path.is_file():
        raise EvalError(f"{path} is not a file")
    commands = []
    luajit = shutil.which("luajit")
    if luajit:
        commands.append([luajit, "-bl", str(path)])
    luac = shutil.which("luac5.1")
    if luac:
        commands.append([luac, "-p", str(path)])
    if not commands:
        raise EvalError("no Lua compiler on PATH: install luajit (or luac5.1) so a parse error fails before the reload")
    for command in commands:
        result = subprocess.run(command, capture_output=True, text=True, check=False)
        if result.returncode != 0:
            detail = (result.stderr or result.stdout).strip()
            if not detail:
                detail = f"{Path(command[0]).name} rejected the snippet"
            raise EvalError(f"{path}: {detail}")


def _origin(name: str) -> str:
    return name.replace("\n", " ").replace("\r", " ").strip() or "a file"


def render(source: str, origin: str, token: str) -> str:
    """The generated inbox chunk, whose format the module docstring describes."""
    body = source if source.endswith("\n") else source + "\n"
    header = (
        f'{TOKEN} = "{token}"; DevSmokeEval = function(...) '
        f"-- generated by tools/devsmoke/eval.py from {_origin(origin)}; do not edit\n"
    )
    return header + body + "end\n"


def toc_text(origin: str) -> str:
    """The generated addon's TOC, named for the AddOns entry the link creates."""
    notes = (
        f"## Notes: Private dev addon: the snippet tools/devsmoke/eval.py wrote from {_origin(origin)}; "
        "!!DevSmoke runs it at login and on /devsmoke eval. Generated, do not edit."
    )
    return "\n".join(["## Interface: 16001", "## Title: Dev Smoke Inbox", notes, "## LoadOnDemand: 1", CHUNK, ""])


def link_inbox(addons: Path, inbox: Path) -> Path:
    """Link the generated folder as its own load-on-demand addon, replacing only our own stale symlink."""
    entry = addons / INBOX
    try:
        if entry.is_symlink():
            if entry.resolve() == inbox.resolve():
                return entry
            entry.unlink()
        elif entry.exists():
            raise EvalError(f"{entry} exists and is not a symlink: remove it so eval can link the generated inbox")
        entry.symlink_to(inbox)
    except OSError as error:
        raise EvalError(f"cannot link {entry}: {error}") from None
    return entry


def write_snippet(source: Path, addons: Path | None = None) -> dict[str, object]:
    """Compile `source`, write it as the inbox chunk, and link the inbox into AddOns."""
    check_source(source)
    try:
        body = source.read_text(encoding="utf-8")
    except OSError as error:
        raise EvalError(f"cannot read {source}: {error}") from None
    addons = addons or default_addons()
    addon = addon_folder(addons)
    inbox = addon / INBOX
    token = secrets.token_hex(8)
    try:
        inbox.mkdir(parents=True, exist_ok=True)
        chunk = inbox / CHUNK
        chunk.write_text(render(body, source.name, token), encoding="utf-8")
        (inbox / f"{INBOX}.toc").write_text(toc_text(source.name), encoding="utf-8")
    except OSError as error:
        raise EvalError(f"cannot write the eval inbox under {inbox}: {error}") from None
    return {
        "snippet": source,
        "chunk": chunk,
        "link": link_inbox(addons, inbox),
        "lines": len(body.splitlines()),
        "token": token,
    }


def clear_inbox(addons: Path | None = None) -> tuple[Path, ...]:
    """Remove the generated inbox and its AddOns link, so a later login has no snippet left to run (#589).

    A proof, smoke or eval session writes a snippet for its own login and calls this when the session ends, including
    when it fails. Only the generated inbox inside a !!DevSmoke checkout is emptied: a stale link that points anywhere
    else is removed without touching its target, and a real folder is left exactly as it is.
    """
    addons = addons or default_addons()
    entry = addons / INBOX
    try:
        expected = (addon_folder(addons) / INBOX).resolve()
    except EvalError:
        expected = None
    removed: list[Path] = []
    if entry.is_symlink():
        target = entry.resolve()
        try:
            entry.unlink()
        except OSError as error:
            raise EvalError(f"cannot remove {entry}: {error}") from None
        removed.append(entry)
        if expected is None or target != expected:
            return tuple(removed)
        inbox = target
    elif entry.exists():
        # A real folder is not ours to delete, and it is what the client loads instead of the checkout inbox.
        return ()
    else:
        if expected is None or not expected.is_dir():
            return ()
        inbox = expected
    for path in (inbox / CHUNK, inbox / f"{INBOX}.toc"):
        try:
            path.unlink()
        except FileNotFoundError:
            pass
        except OSError as error:
            raise EvalError(f"cannot remove {path}: {error}") from None
        else:
            removed.append(path)
    try:
        inbox.rmdir()
    except FileNotFoundError:
        pass
    except OSError:
        # Anything else in the folder is not ours: the chunk and TOC are gone, so the client has nothing to run.
        pass
    else:
        removed.append(inbox)
    return tuple(removed)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("file", type=Path, help="the Lua snippet, run at login and on /devsmoke eval")
    arguments = parser.parse_args(argv)
    try:
        result = write_snippet(arguments.file)
    except EvalError as error:
        print(f"eval: {error}", file=sys.stderr)
        return 2
    print(f"wrote {result['chunk']} from {result['snippet']} ({result['lines']} lines)")
    print(f"linked {result['link']}: load-on-demand, run at login and on /devsmoke eval")
    print("next: /reload, then read DevSmokeDB.eval, or run tools/headless/forever_client.py eval FILE")
    return 0


if __name__ == "__main__":
    sys.exit(main())
